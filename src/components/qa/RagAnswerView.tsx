export function RagBadge({ lang }: { lang: Lang }) {
  return <span className="badge badge--rag">{TXT[lang].badge}</span>;
}

/** 인용 링크를 누르면 접혀 있는 출처 목록을 먼저 펼쳐 이동 대상이 보이게 한다 */
function openSources(e: MouseEvent<HTMLAnchorElement>) {
  e.currentTarget.closest('.qa-answer--rag')?.querySelector('details.rag-sources-wrap')?.setAttribute('open', '');
}

/** 본문의 [1], [2][5] 인용을 출처 목록 링크로 바꾼다 */
function withCitations(text: string, anchor: (n: number) => string, max: number): ReactNode[] {
  return text.split(/(\[\d+\])/g).map((part, i) => {
    const m = /^\[(\d+)\]$/.exec(part);
    const n = m ? Number(m[1]) : 0;
    if (!m || n < 1 || n > max) return <Fragment key={i}>{part}</Fragment>;
    return (
      <a key={i} className="rag-cite" href={`#${anchor(n)}`} onClick={openSources}>
        [{n}]
      </a>
    );
  });
}

/** 빈 줄 = 문단, "- " 로 시작하는 줄 = 목록 */
function AnswerBody({ text, anchor, max }: { text: string; anchor: (n: number) => string; max: number }) {
  return (
    <>
      {text.split(/\n\s*\n/).map((para, i) => {
        const lines = para.split('\n').filter((l) => l.trim());
        if (lines.length > 0 && lines.every((l) => /^\s*[-•]\s/.test(l))) {
          return (
            <ul key={i} className="rag-answer__list">
              {lines.map((l, j) => (
                <li key={j}>{withCitations(l.replace(/^\s*[-•]\s/, ''), anchor, max)}</li>
              ))}
            </ul>
          );
        }
        return (
          <p key={i} className="qa-answer__p">
            {withCitations(lines.join(' '), anchor, max)}
          </p>
        );
      })}
    </>
  );
}

export function RagAnswerView({ msg, lang, time }: { msg: RagMessage; lang: Lang; time: ReactNode }) {
  const x = TXT[lang];
  const anchor = (n: number) => `rag-${msg.id}-${n}`;
  return (
    <article className="qa-answer qa-answer--rag" data-answer="rag">
      <header className="qa-answer__head">
        <RagBadge lang={lang} />
        <span className="qa-answer__via">
          {x.via(msg.sources.length, msg.retrievalMs)}
          {msg.model && ` · ${x.by(msg.model)}`}
        </span>
        {time}
      </header>
      <h4 className="qa-answer__title">{x.title}</h4>

      <section className="qa-answer__block">
        <p className="qa-answer__block-title">{x.answer}</p>
        {msg.answer ? (
          <AnswerBody text={msg.answer} anchor={anchor} max={msg.sources.length} />
        ) : (
          <p className="note note--warn">
            {x.noAnswer[msg.llmStatus]}
            {msg.llmMessage && ` (${msg.llmMessage})`}
          </p>
        )}
        {msg.answer && <p className="note">{x.caution}</p>}
      </section>

      <details className="qa-answer__block rag-sources-wrap">
        <summary className="rag-sources__toggle">{x.showSources(msg.sources.length)}</summary>
        <ol className="rag-sources">
          {msg.sources.map((s) => (
            <li key={s.id} id={anchor(s.rank)} className="rag-source">
              <div className="rag-source__head">
                <span className="rag-source__n">[{s.rank}]</span>
                <strong>{s.doc_id}</strong>
                <span className="num">{x.page(s.page)}</span>
                <span className="rag-source__file" title={s.file}>
                  {s.file}
                </span>
                <span className="rag-source__score num" title="RRF score">
                  {s.rrf_score.toFixed(4)}
                </span>
              </div>
              <details>
                <summary>{x.show}</summary>
                <p className="rag-source__text">{s.text}</p>
              </details>
            </li>
          ))}
        </ol>
      </details>
    </article>
  );
}

/** 질문 기록용 텍스트 (기록 시점 그대로 고정) */
export function ragHistoryAnswer(msg: RagMessage, lang: Lang): QaHistoryAnswer {
  const x = TXT[lang];
  return {
    kind: 'rag',
    title: x.title,
    via: `${x.via(msg.sources.length, msg.retrievalMs)}${msg.model ? ` · ${x.by(msg.model)}` : ''}`,
    blocks: [
      { title: x.answer, lines: [msg.answer ?? `${x.noAnswer[msg.llmStatus]}${msg.llmMessage ? ` (${msg.llmMessage})` : ''}`] },
      {
        title: x.sources(msg.sources.length),
        lines: msg.sources.map((s) => `[${s.rank}] ${s.doc_id} · ${x.page(s.page)} · ${s.file} — ${s.text_preview}`),
      },
    ],
  };
}
